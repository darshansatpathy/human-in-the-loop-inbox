"""Load test of the full approval flow on PostgreSQL: submit, wait (long poll), approve, consume the grant.

HITL_DATABASE_URL=postgresql://... python bench/load.py --flows 400 --concurrency 16 --out docs/performance.md
"""

from __future__ import annotations

import argparse
import asyncio
import time
import uuid
from pathlib import Path

from hitl.config import Settings
from hitl.db import Database, migrate
from hitl.policy import Policy
from hitl.service import Inbox
from hitl.service import Settings as S

ROOT = Path(__file__).resolve().parents[1]


def pct(xs: list[float], p: float) -> float:
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(p * (len(xs) - 1)))] * 1000


async def main(flows: int, concurrency: int, out: str | None) -> None:
    url = Settings().database_url
    migrate(url)
    db = Database(url, min_size=4, max_size=concurrency * 2 + 4)
    await db.open()
    inbox = Inbox(db, Policy.load(ROOT / "policy.yaml"), S(b"bench-key-0123456789abcdef0123456"))
    run = uuid.uuid4().hex[:6]
    await inbox.add_agent(f"bench-{run}")
    await inbox.add_reviewer(f"r1-{run}", "R1", ["support-leads"])
    rev = await inbox.reviewer_for(rid=f"r1-{run}")
    assert rev is not None
    lat: dict[str, list[float]] = {"submit": [], "vote": [], "wake": [], "consume": [], "flow": []}
    sem = asyncio.Semaphore(concurrency)

    async def flow(i: int) -> None:
        async with sem:
            t0 = time.perf_counter()
            args = {"order": f"B-{run}-{i}", "amount": 100 + i % 500}
            v = await inbox.submit(f"bench-{run}", "issue_refund", args, risk="medium", summary="bench")
            lat["submit"].append(time.perf_counter() - t0)
            woke: list[float] = []

            async def waiter() -> dict:
                r = await inbox.wait(v["id"], f"bench-{run}", 30)
                woke.append(time.perf_counter())
                return r

            w = asyncio.create_task(waiter())
            await asyncio.sleep(0.05)
            t1 = time.perf_counter()
            await inbox.vote(v["id"], rev, "approve")
            t2 = time.perf_counter()
            lat["vote"].append(t2 - t1)
            done = await w
            lat["wake"].append(woke[0] - t2)
            t3 = time.perf_counter()
            await inbox.consume_grant(done["grant"], "issue_refund", args, "bench")
            lat["consume"].append(time.perf_counter() - t3)
            lat["flow"].append(time.perf_counter() - t0 - 0.05)

    t = time.perf_counter()
    await asyncio.gather(*(flow(i) for i in range(flows)))
    elapsed = time.perf_counter() - t
    async with db.tx() as cur:
        from hitl.service import verify_chain

        ok, n, _ = await verify_chain(cur)
    await db.close()
    names = {
        "submit": "Submit (policy, insert, audit event)",
        "vote": "Approve (lock, vote, quorum, grant)",
        "wake": "Agent's long poll wakes after the vote",
        "consume": "Executor consumes the grant",
        "flow": "Whole flow, excluding the 50 ms before the vote",
    }
    lines = [
        "# Performance",
        "",
        f"Generated by `python bench/load.py --flows {flows} --concurrency {concurrency}`: the service against one PostgreSQL, "
        "every request through the full flow (submit, an agent long-polling, a reviewer approving, the executor consuming the grant).",
        "",
        f"**{flows} complete approval flows in {elapsed:.1f} s ({flows / elapsed:.0f} a second)** with {concurrency} in parallel. "
        f"Audit chain after the run: {n} events, {'intact' if ok else 'BROKEN'}.",
        "",
        "| Step | p50 ms | p95 ms | p99 ms |",
        "|---|---|---|---|",
    ]
    lines += [f"| {names[k]} | {pct(v, 0.5):.1f} | {pct(v, 0.95):.1f} | {pct(v, 0.99):.1f} |" for k, v in lat.items()]
    lines += [
        "",
        "Every audit event takes a transaction-scoped advisory lock to extend the hash chain, so event appends are serialised; "
        "this is the throughput cost of a single tamper-evident chain.",
    ]
    text = "\n".join(lines) + "\n"
    print(text)
    if out:
        Path(out).write_text(text)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--flows", type=int, default=400)
    ap.add_argument("--concurrency", type=int, default=16)
    ap.add_argument("--out")
    a = ap.parse_args()
    asyncio.run(main(a.flows, a.concurrency, a.out))
